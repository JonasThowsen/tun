#!/usr/bin/env python3
"""Write src/web/ui/icon-data.lisp from a Lucide checkout (spec/ui.md 1).

Usage: python3 -I scripts/ui-icons.py LUCIDE-CHECKOUT

ICONS below is the set Tun carries; add a Lucide name and run this again.
Only shape elements are kept, so the data passes the renderer's allow-list.
"""

import pathlib
import subprocess
import sys
import xml.etree.ElementTree as ET

ICONS = """
arrow-down arrow-left arrow-right arrow-up arrow-up-down arrow-up-right ban bell building
building-complex calendar calendar-days check check-check chevron-down chevron-left
chevron-right chevron-up chevrons-left chevrons-right chevrons-up-down circle circle-alert
circle-check circle-question-mark circle-x clipboard clock copy download ellipsis
ellipsis-vertical external-link eye eye-off file file-text funnel grip-vertical hash house inbox
info key-round layout-dashboard link list list-checks loader-circle lock log-in log-out mail
menu message-square minus monitor moon package panel-left pencil phone plus receipt refresh-cw
save search send settings shield-check shopping-cart sliders-horizontal square-pen star sun tag
trash triangle-alert truck upload user user-plus users wrench x
banknote trending-down trending-up
""".split()

SHAPES = {"path", "circle", "ellipse", "line", "polyline", "polygon", "rect", "g"}
ATTRIBUTES = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "points",
              "width", "height"}


def lisp_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def node(element):
    tag = element.tag.split("}")[-1]
    if tag not in SHAPES:
        raise SystemExit(f"unexpected element {tag}")
    attributes = " ".join(f":{name} {lisp_string(value)}"
                          for name, value in element.attrib.items() if name in ATTRIBUTES)
    children = " ".join(node(child) for child in element)
    return f"(:{tag} (:@ {attributes}){' ' + children if children else ''})"


def main():
    lucide = pathlib.Path(sys.argv[1])
    revision = subprocess.run(["git", "-C", str(lucide), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    out = pathlib.Path(__file__).resolve().parent.parent / "src/web/ui/icon-data.lisp"
    lines = [
        ";;;; web/ui/icon-data.lisp -- the Lucide icons Tun carries, as markup.",
        f";;;; Generated by scripts/ui-icons.py from Lucide {revision}; do not edit by hand.",
        ";;;; Lucide is ISC licensed (reference/ui-sources.md).",
        "",
        "(in-package #:tun.ui)",
        "",
        "(defparameter +icons+",
    ]
    for i, name in enumerate(sorted(set(ICONS))):
        svg = ET.parse(lucide / "icons" / f"{name}.svg").getroot()
        lines.append(("  '((" if i == 0 else "    (") + f":{name}")
        lines.extend(f"     {node(child)}" for child in svg)
        lines[-1] += ")"
    lines[-1] += ")"
    lines.append('  "Each Lucide icon by name: the shapes inside its 24x24 <svg>.")')
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(set(ICONS))} icons to {out}")


if __name__ == "__main__":
    main()
